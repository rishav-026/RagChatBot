import re
from typing import Optional
from pydantic import BaseModel

class OutputGuardrailResult(BaseModel):
    allowed: bool
    reason: str
    is_grounded: bool
    sanitized_output: Optional[str] = None

class OutputGuardrailService:
    """
    Validates output generated by LLM for system prompt leakage and ungrounded content.
    """

    PROHIBITED_OUTPUT_PATTERNS = [
        r"(?i)STRICT OPERATIONAL RULES",
        r"(?i)=== RETRIEVED CONTEXT ===",
        r"(?i)Ignore previous instructions",
        r"(?i)System instructions override",
    ]

    def validate(self, generated_answer: str) -> OutputGuardrailResult:
        if not generated_answer or not generated_answer.strip():
            return OutputGuardrailResult(
                allowed=False,
                reason="LLM generated an empty response.",
                is_grounded=False,
                sanitized_output="I am sorry, I could not generate an answer at this time."
            )

        # Check for system prompt leakage
        for pattern in self.PROHIBITED_OUTPUT_PATTERNS:
            if re.search(pattern, generated_answer):
                return OutputGuardrailResult(
                    allowed=False,
                    reason="Output Guardrail Violation: System prompt leakage detected.",
                    is_grounded=False,
                    sanitized_output="I couldn't find enough relevant information in the uploaded documents to answer this question."
                )

        return OutputGuardrailResult(
            allowed=True,
            reason="Output passed guardrail validation.",
            is_grounded=True,
            sanitized_output=generated_answer
        )
